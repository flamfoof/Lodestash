#!/usr/bin/env node
// gen-icons.mjs — the typed icon-name union for the web UI, from the one sprite (ADR-0012).
//
// Reads docs/design/icons/icons.svg and writes web/src/ui/icons.generated.ts. An icon name that is
// not in the sprite then fails type-checking instead of rendering an empty box (review R7).
//
//   node scripts/design/gen-icons.mjs [--check]

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const sprite = fs.readFileSync(path.join(ROOT, "docs", "design", "icons", "icons.svg"), "utf8");
const out = path.join(ROOT, "web", "src", "ui", "icons.generated.ts");

const ids = [...sprite.matchAll(/<symbol[^>]*\bid="ls-([^"]+)"/g)].map((m) => m[1]);
if (new Set(ids).size !== ids.length) throw new Error("icons.svg has duplicate symbol ids");

const text = `// Generated by scripts/design/gen-icons.mjs from docs/design/icons/icons.svg — do not edit.
export const ICON_NAMES = [
${ids.map((id) => `  "${id}",`).join("\n")}
] as const;

export type IconName = (typeof ICON_NAMES)[number];
`;

if (process.argv.includes("--check")) {
  const current = fs.existsSync(out) ? fs.readFileSync(out, "utf8").replace(/\r\n/g, "\n") : "";
  if (current !== text) {
    console.error("stale: web/src/ui/icons.generated.ts — run node scripts/design/gen-icons.mjs");
    process.exit(1);
  }
} else {
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, text);
  console.log(`wrote ${path.relative(ROOT, out)} (${ids.length} icons)`);
}
